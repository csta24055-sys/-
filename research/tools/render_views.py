#!/usr/bin/env python3
"""Render human-readable Markdown views from the machine ledgers (ledgers are the source of truth).

    python3 research/tools/render_views.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common import CLAIM_TYPE_JA, companies, company_dir, read_json, research_root  # noqa: E402
from research_gates import load_company  # noqa: E402

HDR = "<!-- generated by tools/render_views.py from ledger/*.jsonl; do not edit by hand -->\n"


def md_sources(d):
    out = [HDR, f"# {d['company']['name_ja']}：出典台帳（COMPANY_SOURCES）\n"]
    if not d["sources"]:
        return "".join(out) + "\n出典はまだ登録されていない（未着手）。\n"
    out.append("| SOURCE_ID | 発行主体 | 文書 | 公開日 | 種別 | 原文確認 | 起源グループ | sha256（先頭12桁） |\n|---|---|---|---|---|---|---|---|\n")
    for s in d["sources"]:
        out.append(f"| {s['source_id']} | {s['publisher']} | [{s['title']}]({s['url']}) | {s['published_at']} | {s['source_type']} | {s['access']} | {s['origin_group_id']} | `{(s.get('sha256') or '')[:12]}` |\n")
    out.append("\n## 検索ログ\n\n| LOG | 日時 | クエリ | 件数 | 採用 | 備考 |\n|---|---|---|---|---|---|\n")
    for s in d["search_log"]:
        ex = "; ".join(f"除外: {e['item']}（{e['reason']}）" for e in s.get("excluded", []))
        out.append(f"| {s['log_id']} | {s['at']} | {s['query']} | {s['results']} | {', '.join(s.get('adopted', []))} | {s.get('status', '')} {s.get('notes', '')} {ex} |\n")
    return "".join(out)


def md_findings(d):
    out = [HDR, f"# {d['company']['name_ja']}：主張一覧（COMPANY_FINDINGS）\n\n"]
    if not d["claims"]:
        return "".join(out) + "主張はまだない（未着手）。\n"
    for x in d["claims"]:
        ev = ", ".join(f"{e['passage_id']}({e['direction']})" for e in x["evidence"])
        out.append(f"- **{x['claim_id']}** [{x['topic_id']}] 【{CLAIM_TYPE_JA[x['claim_type']]}】{x['statement']}  \n  根拠: {ev}／有効性: {x['validity']}" + (f"／注: {x['notes']}" if x.get("notes") else "") + "\n")
    return "".join(out)


def md_hypotheses(d):
    out = [HDR, f"# {d['company']['name_ja']}：競合仮説（COMPANY_HYPOTHESES）\n\n"]
    if not d["hypotheses"]:
        return "".join(out) + "仮説はまだない（未着手）。\n"
    for h in d["hypotheses"]:
        out.append(f"## {h['hypothesis_id']}（{h['status']}）\n\n- 現象: {h['observed_phenomenon']}\n- 説明: {h['explanation']}\n"
                   f"- 予測される観測: {'；'.join(h['expected_observations'])}\n- 反証となる観測: {'；'.join(h['disconfirming_observations'])}\n"
                   f"- 支持: {', '.join(h['evidence_for']) or '—'}／反証: {', '.join(h['evidence_against']) or '—'}\n- 反証検討: {h['counterevidence_notes']}\n- 識別に必要なデータ: {h.get('discriminating_data_needed', '')}\n\n")
    return "".join(out)


def md_open(d):
    out = [HDR, f"# {d['company']['name_ja']}：未解決の問い（COMPANY_OPEN_QUESTIONS）\n\n"]
    qs = [q for q in d["questions"] if q.get("kind") != "ROOT_RESEARCH_CARD" and q.get("status") not in ("ANSWERED",)]
    roots = [q for q in d["questions"] if q.get("kind") == "ROOT_RESEARCH_CARD" and q.get("status") == "NOT_STARTED"]
    out.append(f"未着手のROOT研究カード: {len(roots)}件（各軸の `QUESTIONS.md` 参照）\n\n")
    if qs:
        out.append("| QUESTION_ID | 状態 | 問い | 派生理由 |\n|---|---|---|---|\n")
        for q in qs:
            out.append(f"| {q['question_id']} | {q['status']} | {q['question']} | {q.get('discovery_reason', '')} |\n")
    return "".join(out)


def md_axis_questions(d, axis_id):
    qs = [q for q in d["questions"] if q["axis_id"] == axis_id]
    out = [HDR, f"# {d['company']['name_ja']} / {axis_id}：問い（QUESTIONS）\n\n| QUESTION_ID | 親 | 種別 | 状態 | 問い | 一次情報源ルート |\n|---|---|---|---|---|---|\n"]
    for q in qs:
        out.append(f"| {q['question_id']} | {q.get('parent_question_id') or ''} | {q['kind']} | {q['status']} | {q['question']} | {'／'.join(q.get('source_route', []))} |\n")
    return "".join(out)


def md_axis_sources(d, axis_id):
    psg = {p["passage_id"]: p for p in d["passages"]}
    used = sorted({psg[e["passage_id"]]["source_id"] for x in d["claims"] if x["axis_id"] == axis_id for e in x["evidence"] if e["passage_id"] in psg})
    out = [HDR, f"# {d['company']['name_ja']} / {axis_id}：この軸で使用した出典\n\n"]
    if not used:
        return "".join(out) + "なし（未着手）。\n"
    src = {s["source_id"]: s for s in d["sources"]}
    for sid in used:
        s = src[sid]
        out.append(f"- {sid}：{s['publisher']}「{s['title']}」{s['published_at']} <{s['url']}>\n")
    return "".join(out)


def md_progress(d, status):
    c = d["company"]
    st = status or {}
    lines = [HDR, f"# {c['name_ja']}：研究進捗（COMPANY_PROGRESS）\n\n",
             f"- COMPANY_RESEARCH_STATUS: **{st.get('company_research_status', 'UNKNOWN')}**（報告書: {st.get('report_status', '')}）\n",
             f"- 30軸: PASS {st.get('axes_pass', 0)} / IN_PROGRESS {st.get('axes_in_progress', 0)}\n",
             f"- 240テーマ: {st.get('topics_by_state', {})}\n",
             f"- 問い登録: {st.get('questions_registered', 0)}／出典(DIRECT): {st.get('sources_direct', 0)}／独立起源: {st.get('independent_origin_groups', 0)}／主張: {st.get('claims_by_type', {})}／仮説: {st.get('hypotheses', 0)}\n\n",
             "| 軸 | 状態 | テーマ内訳 |\n|---|---|---|\n"]
    for a, v in (st.get("axes") or {}).items():
        lines.append(f"| {a} | {v['state']} | {v['topics']} |\n")
    return "".join(lines)


def main() -> int:
    root = research_root()
    rows = []
    for c in companies():
        d = load_company(c)
        cdir = company_dir(c)
        status = read_json(cdir / "COMPANY_RESEARCH_STATUS.json", {})
        (cdir / "COMPANY_SOURCES.md").write_text(md_sources(d), encoding="utf-8")
        (cdir / "COMPANY_FINDINGS.md").write_text(md_findings(d), encoding="utf-8")
        (cdir / "COMPANY_HYPOTHESES.md").write_text(md_hypotheses(d), encoding="utf-8")
        (cdir / "COMPANY_OPEN_QUESTIONS.md").write_text(md_open(d), encoding="utf-8")
        (cdir / "COMPANY_PROGRESS.md").write_text(md_progress(d, status), encoding="utf-8")
        for adir in sorted((cdir / "axes").glob("AXIS_*")):
            (adir / "QUESTIONS.md").write_text(md_axis_questions(d, adir.name), encoding="utf-8")
            (adir / "SOURCES.md").write_text(md_axis_sources(d, adir.name), encoding="utf-8")
        rows.append((c, status))
    rs = read_json(root / "research_status.json", {})
    out = [HDR, "# RESEARCH_PROGRESS（会社別）\n\n", f"RESEARCH_STATUS = **{rs.get('RESEARCH_STATUS', 'UNKNOWN')}**（基準日 {rs.get('as_of', '')}）\n\n",
           "| 会社 | COMPANY_RESEARCH_STATUS | 報告書 | 軸PASS | 軸進行中 | テーマ状態 | 主張 | 出典 |\n|---|---|---|---|---|---|---|---|\n"]
    for c, s in rows:
        out.append(f"| {c['name_ja']} | {s.get('company_research_status')} | {s.get('report_status')} | {s.get('axes_pass')}/30 | {s.get('axes_in_progress')} | {s.get('topics_by_state')} | {sum((s.get('claims_by_type') or {}).values())} | {s.get('sources_direct')} |\n")
    out.append(f"\n横断レイヤー: {rs.get('layers', {})}\n")
    (root / "RESEARCH_PROGRESS.md").write_text("".join(out), encoding="utf-8")
    print("rendered views")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
