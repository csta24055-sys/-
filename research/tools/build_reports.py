"""Assemble each company's INTEGRATED_COMPANY_REPORT.md, axis digests, NEXT_STEPS.md and SESSION_LOG.md
from that company's ledgers only.

* The hand-written part of a report lives in companies/{name}/REPORT_SUMMARY.md (総括・因果モデル).
  Without it the report is marked AUTO_DIGEST and the gate does not count it as written.
* An axis SYNTHESIS.md that is still a template (or a previous auto digest) is replaced by an
  AUTO_DIGEST view listing the axis' claims, hypotheses and questions. Hand-written syntheses are never
  touched. AUTO_DIGEST never satisfies the gate's "synthesis_written" check.

    python3 research/tools/build_reports.py [--session S2 --date 2026-11-09]
"""
