OPENISH = ("OPEN", "BLOCKED", "BACKLOG", "PARTIAL", "EVALUATED_UNRESOLVED")


def selects(spec: str, claim: dict) -> bool:
    axis, _, topics = spec.partition(":")
    if claim["axis_id"] != axis:
        return False
    return not topics or claim["topic_id"].split("_")[-1] in topics.split(",")


def claim_line(x: dict, eff: dict) -> str:
    v = eff.get(x["claim_id"], x.get("validity"))
    flag = "（要再確認）" if v == "NEEDS_RECHECK" else ""
    return f"- 【{CLAIM_TYPE_JA.get(x['claim_type'], x['claim_type'])}】{x['statement']}{flag}（{x['claim_id']}／{x['topic_id']}）"


def axis_digest(d: dict, axis_id: str, axis_name: str) -> str | None:
    cl = [x for x in d["claims"] if x["axis_id"] == axis_id]
    hy = [h for h in d["hypotheses"] if h["axis_id"] == axis_id]
    qs = [q for q in d["questions"] if q["axis_id"] == axis_id and q.get("kind") != "ROOT_RESEARCH_CARD"]
    if not (cl or hy or qs):
        return None
    eff = effective_validity(d)
    out = [AUTO_DIGEST_MARKER,
           f"# {d['company']['name_ja']} / {axis_id} {axis_name}：初期調査ダイジェスト（自動生成）", "",
           f"> COMPANY_ID: `{d['company']['company_id']}` / 基準日: {AS_OF}",
           "> **これは台帳から機械的に並べた一覧で、分析レポートではない。** 研究ゲートは自動ダイジェストを「執筆済みの統合」と見なさないため、この軸のテーマはこのままではPASSにならない。", ""]
    by_t = defaultdict(list)
    for x in cl:
        by_t[x["topic_id"]].append(x)
    out.append("## 主張（テーマ別）")
    for t in sorted(by_t):
        out.append(f"\n### {t}")
        out += [claim_line(x, eff) for x in by_t[t]]
    if hy:
        out.append("\n## 競合仮説")
        out += [f"- {h['hypothesis_id']}（{h['status']}）{h['explanation']}" for h in hy]
    if qs:
        out.append("\n## 問い")
        out += [f"- {q['question_id']}（{q['status']}）{q['question']}" for q in qs]
    return "\n".join(out) + "\n"


def build_report(d: dict, status: dict) -> str:
    c = d["company"]
    cdir = d["dir"]
    eff = effective_validity(d)
    summary_p = cdir / "REPORT_SUMMARY.md"
    summary = summary_p.read_text(encoding="utf-8").strip() if summary_p.exists() else ""
    head = [f"<!-- generated by tools/build_reports.py from this company's ledgers; hand-written part: REPORT_SUMMARY.md -->"]
    if not summary:
        head.append(AUTO_DIGEST_MARKER)
    tb = status.get("topics_by_state", {})
    head += [f"# {c['name_ja']}：独立総合インテリジェンス研究書", "",
             f"> COMPANY_ID: `{c['company_id']}`（{c['name_en']}）／ 基準日: {AS_OF} ／ 研究ゲート: **{status.get('company_research_status', '?')}**",
             f"> 30軸: PASS {status.get('axes_pass', 0)}・進行中 {status.get('axes_in_progress', 0)} ／ 240テーマ: {tb} ／ 主張 {sum((status.get('claims_by_type') or {}).values())}（{status.get('claims_by_type')}）",
             "> 本書はこの会社の資料だけで成立し、他社の研究書・出典IDを参照しない。各文末のIDから原文位置（台帳）へ遡れる。未調査の章は未調査と明記する。", ""]
    if summary:
        head += ["## 総括（研究者による統合・手書き）", "", summary, ""]
    else:
        head += ["## 総括", "（未執筆：REPORT_SUMMARY.md がないため、本書は台帳の自動ダイジェストにとどまる）", ""]
    body = []
    for n, title, specs in CHAPTERS:
        body.append(f"## {n}. {title}")
        if n == 10:
            if d["hypotheses"]:
                body += ["| 仮説 | 説明 | 評価 | 反証の記録 |", "|---|---|---|---|"]
                for h in d["hypotheses"]:
                    body.append(f"| {h['hypothesis_id']} | {h['explanation']} | {h['status']} | {len(h.get('evidence_against', []))}件 |")
            for m in d["models"]:
                body.append(f"- モデル {m['model_id']}：{m['name']}（{m['method']}）")
        if n == 12:
            body.append("総括の因果説明（上記）が現時点の会社固有モデル。30軸を結ぶ定量モデルは未構築。")
        if n == 13:
            if d["relations"]:
                for r in d["relations"]:
                    amt = f"、{r['amount']['value']} {r['amount']['unit']}" if r.get("amount") else ""
                    body.append(f"- {r['relation_id']}：{r['from_entity']} → {r['to_entity']}（{r['type']}{amt}、{r['status']}）")
            else:
                body.append("（この会社の台帳で確認した関係エッジはまだない）")
            body.append("- 他の総合商社との関係は、会社別研究の後に `cross_company/` で双方の原文IDを突き合わせて扱う（本書には転記しない）。")
        if n == 14:
            qs = [q for q in d["questions"] if q.get("kind") != "ROOT_RESEARCH_CARD" and q.get("status") in ("OPEN", "BLOCKED", "BACKLOG")]
            for q in qs:
                body.append(f"- {q['question_id']}（{q['status']}）{q['question']}")
            unk = [x for x in d["claims"] if x["claim_type"] == "UNKNOWN"]
            body += [claim_line(x, eff) for x in unk]
            body.append(f"- 未着手のROOT研究カード：{sum(1 for q in d['questions'] if q.get('kind') == 'ROOT_RESEARCH_CARD' and q.get('status') == 'NOT_STARTED')}件")
        if n == 15:
            snaps = sorted(p.name for p in (cdir / "snapshots").iterdir() if p.is_dir())
            body.append(f"- スナップショット：{', '.join(snaps)}")
            body.append(f"- 再確認イベント：{len(d['status_events'])}件（ledger/claim_status_events.jsonl）")
            body.append("- ゲートの正本は `COMPANY_RESEARCH_STATUS.json`、更新履歴は `UPDATE_HISTORY.md`。")
        picked = [x for x in d["claims"] if any(selects(s, x) for s in specs)]
        if specs and n != 14:
            if picked:
                body += [claim_line(x, eff) for x in picked]
            else:
                body.append(f"（未調査：{', '.join(s.split(':')[0] for s in specs)}）")
        elif n == 14:
            body += [claim_line(x, eff) for x in picked]
        body.append("")
    return "\n".join(head + body)


def next_steps(d: dict) -> str:
    c = d["company"]
    qs = [q for q in d["questions"] if q.get("kind") != "ROOT_RESEARCH_CARD" and q.get("status") in ("OPEN", "BLOCKED", "BACKLOG")]
    order = {"BLOCKED": 2, "OPEN": 0, "BACKLOG": 1}
    qs.sort(key=lambda q: (order[q["status"]], q["question_id"]))
    untouched = [a for a in sorted({x["axis_id"] for x in [{"axis_id": a["axis_id"]} for a in axes()]})
                 if not any(x["axis_id"] == a for x in d["claims"]) and not any(q["axis_id"] == a and q.get("kind") != "ROOT_RESEARCH_CARD" for q in d["questions"])]
    lines = ["<!-- generated by tools/build_reports.py from open questions; edit the questions, not this file -->",
             f"# {c['name_ja']}：次回再開手順（NEXT_STEPS）", "",
             "## 1. 未解決の問い（優先順：OPEN → BACKLOG → BLOCKED）", ""]
    lines += [f"- [{q['status']}] {q['question_id']}：{q['question']}（{q.get('discovery_reason', '')}）" for q in qs] or ["- なし"]
    lines += ["", "## 2. まだ一次資料の主張がない軸", "", "- " + (", ".join(untouched) if untouched else "なし（全軸に初期主張あり）"),
              "", "## 3. 手順", "",
              f"1. `python3 research/research_gates.py --company {c['company_id']}` で現状を確認する。",
              "2. 一次資料を取得し、`research/tools/evidence_builder.py` 用のspecを書く（抜粋は原文頁と機械照合される）。",
              "3. 主張・仮説・問いを追加したら、該当軸の SYNTHESIS.md を手書きで更新する（自動ダイジェストのままではPASSにならない）。",
              "4. `research/run_all.sh` が全て通ってからコミットする。"]
    return "\n".join(lines) + "\n"


SESSION_HEADER = ("| セッション | 日付 | 収集資料数 | 確認済み事実（FACT）数 | 独立起源グループ数 | PASSテーマ | 未検証仮説 | 次回着手（OPENの問い） "
                  "| 主張数 | 着手テーマ数 | 独立起源（一次の根拠のみ） | 再確認周期のないCURRENT主張 |\n"
                  "|---|---|---|---|---|---|---|---|---|---|---|---|\n")


def session_log(d: dict, status: dict, session: str, date: str) -> str:
    facts = sum(1 for x in d["claims"] if x["claim_type"] == "FACT")
    unverified = [h["hypothesis_id"] for h in d["hypotheses"] if h["status"] in ("UNRESOLVED", "SUPPORTED_WEAKLY", "WEAKENED")]
    passed = [t["topic_id"] for t in status.get("topics", []) if t.get("state") == "PASS"]
    started = sum(1 for t in status.get("topics", []) if t.get("state") in ("IN_PROGRESS", "PASS"))
    nxt = [q["question_id"] for q in d["questions"] if q.get("kind") != "ROOT_RESEARCH_CARD" and q.get("status") == "OPEN"][:5]
    psg = {p["passage_id"]: p for p in d["passages"]}
    src = {s["source_id"]: s for s in d["sources"]}
    primary = {src.get(psg[e["passage_id"]]["source_id"], {}).get("origin_group_id") for x in d["claims"] for e in x.get("evidence", [])
               if e.get("passage_id") in psg and e.get("relation", "PRIMARY_DIRECT") in ("PRIMARY_DIRECT", "PRIMARY_INDIRECT")}
    no_recheck = sum(1 for x in d["claims"] if x.get("validity") == "CURRENT" and not x.get("info_class"))
    return (f"| {session} | {date} | {len(d['sources'])} | {facts} | {len({s.get('origin_group_id') for s in d['sources']})} | "
            f"{len(passed)}（{', '.join(passed) or '—'}） | {len(unverified)}（{', '.join(unverified) or '—'}） | {', '.join(nxt) or '—'} "
            f"| {len(d['claims'])} | {started} | {len(primary - {None})} | {no_recheck} |\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--session")
    ap.add_argument("--date")
    a = ap.parse_args(argv)
    names = {x["axis_id"]: x["axis_name"] for x in axes()}
    for c in companies():
        d = load_company(c)
        cdir = company_dir(c)
        status = read_json(cdir / "COMPANY_RESEARCH_STATUS.json", {})
        for axis_id, syn in d["synthesis"].items():
            if syn is None or (TEMPLATE_MARKER not in syn and AUTO_DIGEST_MARKER not in syn):
                continue  # hand-written: never overwrite
            dig = axis_digest(d, axis_id, names[axis_id])
            if dig:
                (cdir / "axes" / axis_id / "SYNTHESIS.md").write_text(dig, encoding="utf-8")
        (cdir / "INTEGRATED_COMPANY_REPORT.md").write_text(build_report(d, status), encoding="utf-8")
        (cdir / "NEXT_STEPS.md").write_text(next_steps(d), encoding="utf-8")
        if a.session:
            p = cdir / "SESSION_LOG.md"
            if not p.exists():
                p.write_text(f"# {c['name_ja']}：セッション記録\n\n" + SESSION_HEADER, encoding="utf-8")
            text = p.read_text(encoding="utf-8")
            lines = text.splitlines(keepends=True)
            for i, line in enumerate(lines):  # widen an older 8-column header in place; earlier rows keep their cells
                if line.startswith("| セッション |") and "主張数" not in line:
                    lines[i:i + 2] = [SESSION_HEADER]
                    text = "".join(lines)
                    break
            p.write_text(text if f"| {a.session} |" in text else text + session_log(d, status, a.session, a.date or ""), encoding="utf-8")
    print("built reports, digests, next steps" + (f", session log {a.session}" if a.session else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
