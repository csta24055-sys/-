#!/usr/bin/env python3
"""Build the cross-company comparison layer (directive STEP 7) from each company's OWN ledger.

Nothing here is written back into company folders. Every number in the comparison table carries the
observation ID of the company that reported it; companies without an observation show a gap, not an
estimate. Relations come from cross_company/relations.jsonl (validated by research_gates.py).

    python3 research/tools/build_cross_company.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import AS_OF, companies, company_dir, read_json, read_jsonl, research_root  # noqa: E402

FY = "FY2025(2026-03-31)"
METRICS = [
    ("net_income_attributable", "当期利益（親会社帰属）", "億円"),
    ("roe_company_definition", "ROE（各社定義）", "%"),
    ("equity_ratio_company_definition", "自己資本比率（各社定義）", "%"),
    (("net_der_reported", "net_der"), "ネットDER（各社定義）", "倍"),
    ("employees_consolidated", "連結従業員", "人"),
    ("employees_parent", "本体従業員", "人"),
    ("avg_salary_parent", "本体平均年間給与", "万円"),
]


def to_unit(o: dict, target: str):
    v, u = o["value"], o["unit"]
    if target == "億円":
        return int(round(v / 100)) if u == "百万円" else v
    if target == "万円":
        return int(round(v / 10000)) if u == "円" else v
    return v


def main() -> int:
    root = research_root()
    status = read_json(root / "research_status.json", {})
    by_status = {c["company_id"]: c for c in status.get("companies", [])}
    rows = []
    for c in companies():
        obs = read_jsonl(company_dir(c) / "ledger" / "observations.jsonl")
        idx = {(o["variable"], o["period"]): o for o in obs}
        cells = []
        for var, _label, unit in METRICS:
            names = var if isinstance(var, tuple) else (var,)
            o = next((idx[(n, FY)] for n in names if (n, FY) in idx), None)
            cells.append(f"{to_unit(o, unit):,}<br/><sub>{o['observation_id']}</sub>" if o else "—")
        st = by_status.get(c["company_id"], {})
        rows.append(f"| {c['name_ja']} | {st.get('company_research_status', '?')} | " + " | ".join(cells) + " |")

    pf = []
    for c in companies():
        srcs = read_jsonl(company_dir(c) / "ledger" / "sources.jsonl")
        items = [f"{s['published_at']} {s['publisher'].split('（')[-1].rstrip('）')}：{s['title'][:28]}（{s['source_id']}）"
                 for s in srcs if "国際協力銀行" in s["publisher"] or "日本貿易保険" in s["publisher"]]
        pf.append(f"| {c['name_ja']} | {len(items)} | {'<br/>'.join(items) or '該当なし（2025〜2026年度の公表文検索）'} |")

    rel = read_jsonl(root / "cross_company" / "relations.jsonl")
    name = {c["company_id"]: c["name_ja"] for c in companies()}
    rrows = [f"| {r['relation_id']} | {r['type']} | {name[r['company_a']]} ↔ {name[r['company_b']]} | {r.get('via_entity') or ''} | {r['status']} | "
             f"{r.get('evidence_level', '—')} | {', '.join(r.get('evidence_a', [])) or '—'} | {', '.join(r.get('evidence_b', [])) or '—'} | "
             f"{', '.join(x['passage_id'] for x in r.get('third_party_evidence', [])) or '—'} |" for r in rel]
    # degree per company and type (existence of edges only; not a measure of influence)
    types = sorted({r["type"] for r in rel})
    deg = []
    for c in companies():
        cid = c["company_id"]
        mine = [r for r in rel if cid in (r["company_a"], r["company_b"])]
        partners = sorted({name[r["company_b"] if r["company_a"] == cid else r["company_a"]] for r in mine})
        deg.append(f"| {c['name_ja']} | {len(mine)} | " + " | ".join(str(sum(1 for r in mine if r['type'] == ty)) for ty in types)
                   + f" | {'、'.join(partners) or '—'} |")
    expo = read_jsonl(root / "cross_company" / "common_exposures.jsonl")
    erows = []
    for e in expo:
        for c in companies():
            ids = e.get("claims", {}).get(c["company_id"], [])
            erows.append(f"| {e['exposure_id']} | {c['name_ja']} | {', '.join(ids) or '台帳で未確認'} |")
    ehead = "\n".join(f"- **{e['exposure_id']}**：{e['event']}（{e.get('observed_in', '')}）。{e.get('notes', '')}" for e in expo)

    md = f"""<!-- generated by tools/build_cross_company.py; company ledgers are the source of truth -->
# 会社間比較・接続レイヤー（COMPARATIVE_REPORT）

> 状態：**{status.get('layers', {}).get('cross_company', 'PARTIAL')}**（基準日 {AS_OF}）。このレイヤーは8社それぞれの独立研究の**上に載る派生物**で、各社の研究書を上書きしない。
> 各社が自社の資料で報告した値を並べているだけで、定義の違いは補正していない。どの会社のゲートもPASSしていないため、比較は暫定である。

## 1. 各社が自社資料で報告した標準指標（FY2025＝2026年3月期）

| 会社 | 会社ゲート | {' | '.join(f'{l}（{u}）' for _, l, u in METRICS)} |
|---|---|{'---|' * len(METRICS)}
{chr(10).join(rows)}

**比較上の注意（補正していない定義差）**
- ROE・自己資本比率：分母が「親会社所有者帰属持分」か「株主資本」かで各社が異なる。丸紅の値は統合報告書の財務データ表（監査対象外の任意開示）による。
- ネットDER：リース負債の扱いや分母（株主資本／資本合計）が各社で異なる。丸紅は2022年度に分母を変更している。豊田通商は会社記載の概数（0.3倍）。
- 本体平均給与：賞与・手当の含め方は各社の注記に従う。三井物産は千円単位の開示を換算した。
- 三菱商事の値は2025年度有価証券報告書（EDINET S100YB25）による。三菱商事は有報で実績のネットDERを開示していないため空欄とし、計算値（約0.41倍）は三菱商事の研究書の分析（CLM-C02-0075）にとどめる。
- 本体従業員：三菱商事は提出会社の経営指標の「従業員数」（就業人員4,456名）を採用した。在籍ベース（5,328名）とは異なる。各社の定義は各社の注記に従う。
- 数値の並列は相関・優劣の主張ではない。差の原因は各社の研究書の仮説で個別に扱う。

## 2. 公表資料で確認できた政策金融・政策保険（JBIC・NEXI、2025〜2026年度の公表文検索）

| 会社 | 件数 | 案件（公表日・機関・件名・会社内出典ID） |
|---|---|---|
{chr(10).join(pf)}

検索範囲：JBICの2025・2026年度のプレスリリース本文263件、NEXIの一覧から取得できた30件（網羅性は未確認）。件数は「公表された案件」で、利用の有無や規模の全体を表さない（公表の選択バイアスがある）。

## 3. 会社間の関係エッジ（双方の会社台帳の原文IDで検証）

| ID | 関係型 | 会社 | 経由・対象 | 状態 | 証拠水準 | A社の自社資料 | B社の自社資料 | 第三者資料 |
|---|---|---|---|---|---|---|---|---|
{chr(10).join(rrows)}

- 証拠水準は、引用した原文の出所からゲートが計算する（宣言値と食い違えば `E_EVIDENCE_LEVEL`）。
  - `BOTH_SIDES`（両側確認）：両社がそれぞれ**自社の開示**で同じ関係を記載している。JBIC・JCR等の第三者資料が会社の台帳にあっても、会社側の確認には数えない。
  - `ONE_SIDED`（片側確認）：片方の会社の自社開示だけで確認した。相手側の資料と突き合わせるまで、相手会社の研究には反映しない。
  - `+THIRD_PARTY`（第三者確認）：どちらの会社の開示でもない資料（例：Berkshire Hathawayの株主への手紙）が同じ関係を記載している。
- どのエッジも**関係の存在**を記録するだけで、因果（例：共通株主が両社の経営判断に影響した）は主張しない（`causal: false`）。

### 3.1 会社ごとの接続数（エッジの存在の数で、影響力の大きさではない）

| 会社 | エッジ数 | {' | '.join(types)} | 接続先 |
|---|---|{'---|' * len(types)}---|
{chr(10).join(deg)}

### 3.2 共通の外部ショックへの言及（エッジではない）

{ehead}

| ID | 会社 | 各社の台帳の主張 |
|---|---|---|
{chr(10).join(erows)}

## 4. 未接続・未研究の接続先
- Mitsui-Itochu Iron（XREL-0005）と伊藤忠丸紅住商テクノスチール（XREL-0007）は片側確認のまま。伊藤忠・丸紅の有報本文の検索では該当の記載を見つけられなかった。
- 伊藤忠の米国航空機リース会社への投資は、JCRの記述（第三者）だけで伊藤忠自身の開示がなく、航空機リース市場のエッジ（XREL-0021）に加えていない。
- かどや製油：三菱商事は26.91%を持分法で保有し、三井物産は関係会社のうち有報提出会社として名前を挙げるが、三井物産側の出資比率の記載を確認していない。
- 共通の協調融資銀行：公表資料で確認できたのは三菱商事（三菱UFJ銀行、Aethon案件）と三井物産（みずほ銀行、鉄鉱石案件）のみで、同じ銀行を介した会社間の重なりはまだ見つかっていない。
- 豊田通商・兼松・双日とNational Indemnityの関係はない（Berkshireの手紙の日本の保有一覧は5社のみ）。
"""
    (root / "cross_company" / "COMPARATIVE_REPORT.md").write_text(md, encoding="utf-8")
    print("wrote cross_company/COMPARATIVE_REPORT.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
