    d = {
        "id": id, "box_id": box_id, "title": title, "fiscal_year": fy, "kind": kind,
        "folder": folder, "folder_id": folder_id, "status": status, "topic": topic,
        "link": (BOXF if kind == "フォルダ" else BOX).format(box_id),
        "accessed": ACCESSED,
    }
    d.update({k: kw.get(k, "") for k in (
        "purpose", "conditions", "instruments", "measurements", "raw_data", "methods",
        "results", "conclusions", "limitations", "related", "pages", "version", "notes")})
    return d


