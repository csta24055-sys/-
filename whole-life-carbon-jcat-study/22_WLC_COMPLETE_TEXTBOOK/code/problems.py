# ---------------------------------------------------------------- 共通の計算（素朴な数え上げ）
def C_closed(T, a, b, cycles=(), extra=0):
    """C(T) = a + bT + Σ R·N(T; L) + extra（閉じた式）。"""
    return Fr(a) + Fr(b) * Fr(T) + sum(Fr(R) * n_events(T, L) for R, L in cycles) + Fr(extra)


def C_loop(T, a, b, cycles=(), extra=0):
    """同じ値を、年ごとの運用（最後の年は端数）と事象の一覧から数え上げる。"""
    T = Fr(T)
    tot = Fr(a) + Fr(extra)
    y = 1
    while y - 1 < T:
        tot += Fr(b) * min(Fr(1), T - (y - 1))
        y += 1
    for R, L in cycles:
        t = Fr(L)
        while t < T:
            tot += Fr(R)
            t += Fr(L)
    return tot


def kernel(T, s, ell, g=None):
    """教材の式 (4.4)：κ(T; s, ℓ, g) = [g < T]·r、r = min(ℓ, max(0, T − s))（ℓ > 0）、ℓ = 0 なら 1。g を省くとゲート無し。"""
    T, s = Fr(T), Fr(s)
    if g is not None and not (Fr(g) < T):
        return Fr(0)
    if ell is None:  # 無限の長さ（密度）
        return max(Fr(0), T - s)
    ell = Fr(ell)
    if ell == 0:
        return Fr(1) if (g is not None or s < T) else Fr(0)
    return min(ell, max(Fr(0), T - s))


def knots_eval(T, init, knots):
    """節点形 (4.6)：初期値 + Σ_{u<T} (c0 + c1 T)。"""
    T = Fr(T)
    return Fr(init) + sum(Fr(c0) + Fr(c1) * T for u, c0, c1 in knots if Fr(u) < T)


