def _lap_num(f, s, Tmax=1500, n=600000):
    """数値の積分（台形則）。厳密な式の独立な確認用（浮動小数）。"""
    h = Tmax / n
    tot = 0.5 * (f(0) + f(Tmax) * math.exp(-s * Tmax))
    for i in range(1, n):
        T = i * h
        tot += f(T) * math.exp(-s * T)
    return tot * h


