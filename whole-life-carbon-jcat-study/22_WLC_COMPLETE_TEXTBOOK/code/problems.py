def section_exists(sec: str, headings: set[str]) -> bool:
    return sec in headings


def textbook_headings() -> set[str]:
    hs = set()
    for f in sorted((ROOT / "textbook").glob("ch*.md")):
        for ln in f.read_text(encoding="utf-8").splitlines():
            m = re.match(r"^##\s+(\d+\.\d+)\s", ln)
            if m:
                hs.add(m.group(1))
            m = re.match(r"^##\s+付録\s*([A-Z])", ln)
            if m:
                hs.add("付録" + m.group(1))
    return hs


