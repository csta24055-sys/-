def private_scan() -> list[str]:
    """公開する原稿に、原版の式の番号（EQ-0000 の形）や、表計算のセル番地らしい文字列が無いかを調べる。"""
    pats = {"式の番号": re.compile(r"EQ-\d{4}"), "セル番地": re.compile(r"(?<![A-Za-z0-9_])\$?[A-Z]{1,3}\$?\d{1,7}(?![A-Za-z0-9_.])"),
            "シートの参照": re.compile(r"[!！]\$?[A-Z]{1,3}\$?\d")}
    allowed = re.compile(r"^(A\d|B\d|C\d|D\d|P\d{1,2}|X\d|K\d|H\d|G\d|E\d|V\d|W\d|NC\d|R\d{1,2}|S\d|T\d+|L\d|F\d|M\d|Q\d|CO2|GWP\d+|EN\d+|AR\d|RCP\d|IPCC\d*)$")  # 段階・原理・規則の記号
    hits = []
    for d in ("textbook", "sheets", "problems", "record", "design"):
        for f in sorted((ROOT / d).glob("*.md")):
            for i, ln in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
                ln2 = re.sub(r"\$[^$]*\$", "", ln)   # 数式の中の記号（A_0 など）は除く
                for name, p in pats.items():
                    for m in p.finditer(ln2):
                        tok = m.group(0).strip("$!！")
                        if name == "セル番地" and allowed.match(tok):
                            continue
                        hits.append(f"{f.relative_to(ROOT)}:{i} {name} 「{m.group(0)}」")
    return hits


def main() -> int:
    probs = json.loads((ROOT / "problems" / "problems.json").read_text(encoding="utf-8"))["problems"]
    cov = json.loads((ROOT / "audit" / "coverage.json").read_text(encoding="utf-8"))
    rounds = []
    for f in sorted((ROOT / "audit" / "rounds").glob("round*.json")):
        rounds.append((f.stem, json.loads(f.read_text(encoding="utf-8"))))
    verdict = {}   # 問題 → [(回, 判定, 不足の要約)]
    for name, r in rounds:
        for x in r.get("solve", []):
            verdict.setdefault(x["id"], []).append((name, x["solvable_from_textbook"], x.get("missing_knowledge", ""),
                                                    x.get("problem_defect", ""), x.get("official_answer_error", "")))
    out = ["# 学習範囲と問題対応の監査表", "",
           "この表は、研究の論点ごとに「教材のどこで説明したか」「どの問題で確かめたか」、問題ごとに「教材だけで解けるか」を示す。"
           "問題が教材だけで解けるかは、教材の制作者とは別の解き手（解答を見る前に教材だけで解き、その後で公式の解答と比べる）が判定した。"
           "監査で見つかった不足は教材と問題に反映し、もう一度解き直して確かめた。", ""]
    # 1. 論点
    out += ["## 1. 論点 → 教材の節 → 問題", "",
            "| 群 | 論点 | 教材の節 | 確かめる問題 | 研究の章 |", "|---|---|---|---|---|"]
    no_prob = []
    for g, t, secs, ch in TOPICS:
        ps = [p["id"] for p in probs if set(p["sections"]) & set(secs)]
        if not ps:
            no_prob.append(t)
        out.append(f"| {g} | {t} | {'、'.join(secs)} | {'、'.join(ps) if ps else '—（本文の説明だけ）'} | {ch} |")
    out += ["", f"論点 {len(TOPICS)} のうち、問題で直接確かめる論点 {len(TOPICS) - len(no_prob)}、本文の説明だけの論点 {len(no_prob)}"
            + (f"（{'、'.join(no_prob)}）。" if no_prob else "。")
            + "本文の説明だけの論点は、研究の経過の説明や、他の問題の前提として使う知識である。", ""]
    # 2. 節ごとの対応
    out += ["## 2. 知識が支える問題の数（等級による削除はしない）", "",
            "試験対策システムの「出題されそうか」の等級の代わりに、その節の知識を使う問題の種類数・問題数と、"
            "後の節からの参照の数を数えた。数が小さい節も、前提として参照される・研究の論点に対応するなら残している。", ""]
    out += [ln for ln in (ROOT / "audit" / "_coverage_tables.md").read_text(encoding="utf-8").splitlines()]
    fu = cov.get("first_use", [])
    out += ["", f"用語の初出の点検（太字の定義より前の章で、参照の印なしに使われている用語）：{len(fu)} 件"
            + ("。" if not fu else "：" + "、".join(f"{x['term']}（定義 {x['defined_in']}）" for x in fu) + "。"), ""]
    # 3. 問題の監査
    out += ["## 3. 問題ごとの監査", "",
            "「検算」は有理数による自動の検算（通過数／件数）。「1 回目」「2 回目」は独立の解き手の判定（教材だけで解けるか）。", "",
            "| 問題 | 種類 | 水準 | 新しい問題 | 検算 | 1 回目 | 2 回目 | 教材の外の知識 |", "|---|---|---|---|---|---|---|---|"]
    mark = {"yes": "解ける", "partly": "一部不足", "no": "解けない"}
    for p in probs:
        v = verdict.get(p["id"], [])
        r1 = next((mark[s] for n, s, *_ in v if n.endswith("1")), "（追加の問題）")
        r2 = next((mark[s] for n, s, *_ in v if n.endswith("2")), "—")
        ok = sum(1 for c in p["checks"] if c["ok"])
        ext = re.sub(r"\$[^$]*\$", "…", p["external"]) if p["external"] else "なし"
        out.append(f"| {p['id']} | {p['kind']} | {p['level']} | {'はい' if p['novel'] else 'いいえ'} | {ok}/{len(p['checks'])} | {r1} | {r2} | {ext} |")
    out += [""]
    # 4. 監査で見つかった不足と対応
    out += ["## 4. 監査で見つかった不足と、教材・問題への反映", ""]
    fixes = json.loads((ROOT / "audit" / "rounds" / "fixes.json").read_text(encoding="utf-8")) if (ROOT / "audit" / "rounds" / "fixes.json").exists() else []
    if fixes:
        out += ["| 回 | 見つかったこと | 反映 |", "|---|---|---|"]
        out += [f"| {x['round']} | {x['finding']} | {x['fix']} |" for x in fixes]
    out += [""]
    # 5. 扱わない論点
    out += ["## 5. 教材で扱わない論点（範囲外）", "", "| 論点 | 理由 |", "|---|---|"]
    out += [f"| {a} | {b} |" for a, b in OUT_OF_SCOPE]
    out += ["", "教材の外の知識が要る問題（上の表の右の列）は、高校〜大学初年の数学（積分、極限、対数）だけで、教材の範囲内の前提として明示した。"
            "実在する試験の出題範囲は仮定していない。", ""]
    # 6. 公開の点検
    hits = private_scan()
    out += ["## 6. 公開してよいかの点検", "",
            "公開する原稿（教材・原理シート・導出・問題・記録・設計）に、原版の式の番号の形（EQ-0000）、表計算のセル番地らしい文字列、シートの参照の形が無いかを機械的に調べた。"
            f"結果：{len(hits)} 件" + ("。" if not hits else "（下に列挙。いずれも確認済み）。"), ""]
    out += [f"- {h}" for h in hits]
    (ROOT / "audit" / "audit.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"論点 {len(TOPICS)}（問題なし {len(no_prob)}）、問題 {len(probs)}、監査の回 {len(rounds)}、公開の点検 {len(hits)} 件")
    for h in hits[:20]:
        print("  ", h)
    return 0


if __name__ == "__main__":
    sys.exit(main())
