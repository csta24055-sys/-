KEYS = ["b1", "b2", "b3", "b4", "b5", "b6", "b7", "b8"]


def main():
    digest = json.load(open(DIGEST, encoding="utf-8"))
    ids = [u["id"] for u in digest["units"]]
    by_id = {}
    for uid, sc, rat, rep in S:
        assert uid not in by_id, "duplicate " + uid
        assert len(sc) == 8, uid
        by_id[uid] = (sc, rat, rep)
    missing = [i for i in ids if i not in by_id]
    extra = [i for i in by_id if i not in ids]
    assert not missing and not extra, (missing, extra)

    scores = []
    for uid in ids:
        sc, rat, rep = by_id[uid]
        entry = {"id": uid}
        for k, v in zip(KEYS, sc):
            assert isinstance(v, int) and 0 <= v <= 3, (uid, k, v)
            entry[k] = v
        entry["rationale"] = rat
        entry["replacement_idea"] = rep
        scores.append(entry)

    out = {"judge": "algebraic_unification", "scores": scores}
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")

    # ---- verification: reload from disk ----
    chk = json.load(open(OUT, encoding="utf-8"))
    assert chk["judge"] == "algebraic_unification"
    assert len(chk["scores"]) == 70, len(chk["scores"])
    assert [e["id"] for e in chk["scores"]] == ids
    for e in chk["scores"]:
        assert list(e.keys()) == ["id"] + KEYS + ["rationale", "replacement_idea"], e["id"]
        for k in KEYS:
            assert type(e[k]) is int and 0 <= e[k] <= 3, (e["id"], k)
        assert e["rationale"].strip() and e["replacement_idea"].strip(), e["id"]
    print("OK: loads, entries =", len(chk["scores"]), ", ids match digest order, all b1..b8 are ints in 0..3")

    tot = [(sum(e[k] for k in KEYS), i, e["id"]) for i, e in enumerate(chk["scores"])]
    ranked = sorted(tot, key=lambda t: (-t[0], t[1]))
    print("top:", [(i, s) for s, _, i in ranked[:17]])
    print("bottom:", [(i, s) for s, _, i in ranked[-8:]])
    for k in KEYS:
        dist = [sum(1 for e in chk["scores"] if e[k] == v) for v in range(4)]
        print(k, "count of 0/1/2/3 =", dist)
    print("distinct score vectors:", len({tuple(e[k] for k in KEYS) for e in chk["scores"]}))


main()
